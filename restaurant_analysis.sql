-- Restaurant Sales Analysis (MySQL)
-- Dataset: Restaurant Orders (Maven Analytics), Jan-Mar 2023
-- Tables: menu_items (menu_item_id, item_name, category, price)
--         order_details (order_details_id, order_id, order_date, order_time, item_id)

USE restaurant;

-- Q1. How many unique orders did the restaurant receive?
SELECT COUNT(DISTINCT order_id) AS total_orders
FROM order_details;

-- Q2. All menu items with category and price, and the number of items in each category
SELECT item_name, category, price
FROM menu_items
ORDER BY category, price DESC;

SELECT category, COUNT(*) AS items_in_category
FROM menu_items
GROUP BY category;

-- Q3. The 5 most expensive menu items
SELECT item_name, category, price
FROM menu_items
ORDER BY price DESC
LIMIT 5;

-- Q4. Items sold from each category
SELECT
    menu_items.category,
    COUNT(order_details.item_id) AS items_sold
FROM order_details
JOIN menu_items
    ON order_details.item_id = menu_items.menu_item_id
GROUP BY menu_items.category
ORDER BY items_sold DESC;

-- Q5. The 10 most ordered menu items
SELECT
    menu_items.item_name,
    menu_items.category,
    COUNT(order_details.item_id) AS quantity_sold
FROM menu_items
JOIN order_details
    ON menu_items.menu_item_id = order_details.item_id
GROUP BY menu_items.item_name, menu_items.category
ORDER BY quantity_sold DESC
LIMIT 10;

-- Q6. Revenue generated by each category
SELECT
    menu_items.category,
    ROUND(SUM(menu_items.price), 2) AS revenue_generated
FROM menu_items
JOIN order_details
    ON menu_items.menu_item_id = order_details.item_id
GROUP BY menu_items.category
ORDER BY revenue_generated DESC;

-- Q7. Orders and revenue on each day
SELECT
    order_details.order_date,
    COUNT(DISTINCT order_details.order_id) AS total_num_of_orders,
    ROUND(SUM(menu_items.price), 2) AS total_revenue_generated
FROM order_details
JOIN menu_items
    ON order_details.item_id = menu_items.menu_item_id
GROUP BY order_details.order_date
ORDER BY order_details.order_date;

-- Q8. At what times of the day do customers order the most?
SELECT
    HOUR(order_time) AS order_hour,
    COUNT(DISTINCT order_id) AS total_orders
FROM order_details
GROUP BY HOUR(order_time)
ORDER BY total_orders DESC;

-- Q9. Menu items that generated more than $2,000 in revenue
SELECT
    menu_items.item_name,
    menu_items.category,
    COUNT(order_details.item_id) AS quantity_sold,
    ROUND(SUM(menu_items.price), 2) AS total_revenue
FROM menu_items
JOIN order_details
    ON menu_items.menu_item_id = order_details.item_id
GROUP BY menu_items.item_name, menu_items.category
HAVING SUM(menu_items.price) > 2000
ORDER BY total_revenue DESC;

-- Q10. Top 3 most ordered items within each category
WITH item_sales AS (
    SELECT
        menu_items.category,
        menu_items.item_name,
        COUNT(order_details.item_id) AS quantity_sold
    FROM menu_items
    JOIN order_details
        ON menu_items.menu_item_id = order_details.item_id
    GROUP BY menu_items.category, menu_items.item_name
),
ranked_items AS (
    SELECT
        category,
        item_name,
        quantity_sold,
        RANK() OVER (PARTITION BY category ORDER BY quantity_sold DESC) AS item_rank
    FROM item_sales
)
SELECT category, item_name, quantity_sold, item_rank
FROM ranked_items
WHERE item_rank <= 3
ORDER BY category, item_rank;

-- Q11. Revenue in each month, ranked from highest to lowest
WITH monthly_revenue AS (
    SELECT
        MONTH(order_date) AS order_month,
        SUM(menu_items.price) AS total_revenue
    FROM order_details
    JOIN menu_items
        ON order_details.item_id = menu_items.menu_item_id
    GROUP BY MONTH(order_date)
)
SELECT
    order_month,
    ROUND(total_revenue, 2) AS total_revenue,
    RANK() OVER (ORDER BY total_revenue DESC) AS revenue_rank
FROM monthly_revenue
ORDER BY revenue_rank;
